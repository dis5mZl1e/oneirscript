"""材料反应配方表（2026-09-18）：液液 / 气气 / 液气 / 其他（墙·地板参与）。

设计原则：

- **产物以现有材料为主**——29 条配方里只有 8 个新物质（5 液 3 气），
  其余产物都是已有液体/气体/墙体/地板变体。
- **混合类（液液/气气/液气）全量转化、总量守恒**：两种材料相遇即整体
  变成产物（上限 100），与「水被其他液体同化」的既有口径一致，
  静默、无消息、无随机。
- **其他类逐拍结算**（熔穿/崩解/脆裂/凝固/冻结），每种反应每层只播报
  一次（运行期记录，不进存档），与超临界流体剥蚀的播报模式一致。
- 与掉落物完全无关：配方只改地图材料，不碰任何生成/掉落表。

代码入口：

- 液液混合 → ``core.materials_sim._mix_liquids`` 头部的配方查询。
- 气气混合 → ``core.materials_sim._resolve_material_arrivals`` 头部的配方查询。
- 液气与其他 → ``core.materials_sim._simulate_recipe_reactions``（每模拟拍）。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class ReactionDef:
    """一条材料反应配方。

    ``mechanism`` 决定结算方式：

    - ``mix``：混合全量转化（液液/气气共用，总量守恒、上限 100）。
    - ``lg_convert``：液气同格全量转化（液体≥10 且气体≥10 才触发；
      产物是液体时气体并入液量，产物是气体时液量并入气量）。
    - ``freeze_wall``：液态蜡遇冷凝固——``reactant_a`` 液体格与
      ``reactant_b``（液氮/液氦）相邻时凝成 ``product`` 墙体。
    - ``freeze_floor``：水面遇冻结冰——``reactant_a`` 液体格与
      ``reactant_b`` 相邻时液体凝结为 ``product`` 地板变体。
    - ``wall_melt``：``reactant_a`` 液体渗进相邻固体墙，按 damage 扣完整度，消耗 consumption 点液体，
      破墙后在原地留下少量该液体。
    - ``wall_bust_gas``：``reactant_b`` 液体剧烈溶蚀 ``reactant_a`` 墙，
      墙崩解并放出 ``product`` 气体 20 点。
    - ``wall_shatter``：``reactant_a`` 墙与 ``reactant_b`` 液体相邻，
      按 damage 扣完整度并消耗寒液（脆裂）。
    """

    category: str       # 液液反应 / 气气反应 / 液气反应 / 其他反应
    reactant_a: str
    reactant_b: str
    product: str        # 产物材料名（墙/地板类为产物墙种或地板变体名）
    product_type: str   # 液体 / 气体 / 墙体 / 地板 / 机制
    note: str           # 主题说明（Excel 与图鉴口径）
    mechanism: str
    message: str = ""   # 触发播报（混合类为空=静默；其他类每层每种一次）
    # 腐蚀/脆裂的有限资源预算；混合与机关类配方不使用这些字段。
    damage: int = 0
    min_amount: int = 0
    consumption: int = 0


