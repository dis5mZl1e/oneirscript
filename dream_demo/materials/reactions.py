# ---- 「不稳定」标签反应集（2026-09-19）----
# 这些液体/气体带「不稳定」标记：任意两种不同材料混合时若至少一方不稳定、
# 且没有精确配方命中，按「不稳定混合」处理——起火（50%）或爆炸（50%）。
# 产物遵循同格归一：归一由 _mix_liquids/_resolve_material_arrivals 完成。
VOLATILE_LIQUIDS: frozenset[str] = frozenset({"燃油", "熔融蜡烛", "血蜡膏", "纸浆"})
VOLATILE_GASES: frozenset[str] = frozenset({"可燃气体", "酒精蒸气", "电浆雾"})


def unstable_mix(kinds) -> bool:
    """混合物里是否至少一方带不稳定标签（且确有两种不同材料）。

    水是基底稀释剂：含水时不按不稳定混合处理（水把反应压下去）。
    """
    present = {kind for kind in kinds if kind}
    if len(present) < 2 or "水" in present:
        return False
    return bool(present & (VOLATILE_LIQUIDS | VOLATILE_GASES))


def _has_inert_reactant(recipe: ReactionDef) -> bool:
    return recipe.reactant_a in INERT_REACTION_PRODUCTS or recipe.reactant_b in INERT_REACTION_PRODUCTS


