# 稀有液态记忆：带接触征兆（专属机制）的全部液体。
RARE_LIQUIDS: tuple[str, ...] = tuple(
    name for name in LIQUID_DEFINITIONS if name not in COMMON_LIQUIDS
)


def is_common_material(name: str) -> bool:
    """该材料能否被不定模板抽到（含墙体/固体/液体三类）。"""
    return name in COMMON_MATERIALS


def unclassified_walls() -> tuple[str, ...]:
    """既不在常见池、也不在稀有名单里的墙种（应为空；供测试与审计使用）。"""
    known = set(COMMON_WALLS) | set(COMMON_SOLIDS) | set(RARE_WALLS)
    return tuple(name for name in WALL_DEFINITIONS if name not in known)
