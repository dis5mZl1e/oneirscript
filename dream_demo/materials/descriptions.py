def material_effect_description(name: str) -> str:
    """地板的确切作用独立于形象介绍，数值读取实际定义。"""
    from .floors import FLOOR_DEFINITIONS
    from ..i18n import tr
    definition = FLOOR_DEFINITIONS.get(name)
    if definition is None:
        return ''
    parts = []
    if definition.protects_plants:
        parts.append(tr('踩踏不会折断高丛。'))
    if definition.flow_divisor > 1:
        parts.append(tr('液体扩散速度降为原来的 1/{n}。', n=definition.flow_divisor))
    if definition.sight_bonus:
        parts.append(tr('站在其上，视野 +{n} 格。', n=definition.sight_bonus))
    if definition.sound_reduction:
        parts.append(tr('声响半径减少 {n} 格，至少保留 1 格。', n=definition.sound_reduction))
    if definition.bare:
        parts.append(tr('植物不能在其上生长。'))
    if definition.evaporation_bonus:
        parts.append(tr('每次挥发额外蒸去 {n} 单位液体。', n=definition.evaporation_bonus))
    if definition.liquid_absorb:
        parts.append(tr('每 2 回合吸去 {n} 单位液体，不产生气体。', n=definition.liquid_absorb))
    if definition.flow_bonus:
        parts.append(tr('液体每次可流出的量增至 {n} 倍。', n=1 + definition.flow_bonus))
    if definition.gas_dissipation_bonus:
        parts.append(tr('气体每次消散额外减少 {n} 单位。', n=definition.gas_dissipation_bonus))
    if definition.scald_lucidity:
        parts.append(tr('每 3 回合造成清醒创伤 {n}；稳定意识不受伤。', n=definition.scald_lucidity))
    return ' '.join(parts)


def material_description(name: str) -> str:
    """按材料名查一句功能介绍；查不到返回空串（面板自动跳过介绍行）。"""
    return (
        FLOOR_DESCRIPTIONS.get(name)
        or WALL_DESCRIPTIONS.get(name)
        or LIQUID_DESCRIPTIONS.get(name)
        or GAS_DESCRIPTIONS.get(name)
        or PLANT_DESCRIPTIONS.get(name)
        or ""
    )


def every_material_has_a_description() -> list[str]:
    """自检：所有目录表里的材料名都有介绍（测试用）。返回缺失名单。"""
    missing: list[str] = []
    for name in WALL_DEFINITIONS:
        if name not in WALL_DESCRIPTIONS:
            missing.append(f"墙体:{name}")
    for name in LIQUID_DEFINITIONS:
        if name not in LIQUID_DESCRIPTIONS:
            missing.append(f"液体:{name}")
    for name in GAS_DEFINITIONS:
        if name not in GAS_DESCRIPTIONS:
            missing.append(f"气体:{name}")
    for plant in PLANT_KINDS:
        if plant.name not in PLANT_DESCRIPTIONS:
            missing.append(f"植物:{plant.name}")
    return missing
