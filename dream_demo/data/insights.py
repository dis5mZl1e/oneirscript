def event_insight_candidates(event_id: str, primary: str | None) -> tuple[str, ...]:
    candidates = ([primary] if primary else []) + list(EVENT_INSIGHT_EXTRAS.get(event_id, ()))
    return tuple(dict.fromkeys(candidates))


def choose_event_insight(candidates: tuple[str, ...], owned, rng) -> str | None:
    """在候选里等权挑一条尚未拥有的；全都有时返回旧主条目（交给原去重提示）。"""
    if not candidates:
        return None
    fresh = [name for name in candidates if name not in owned]
    if not fresh:
        return candidates[0]
    return fresh[rng.randrange(len(fresh))]
